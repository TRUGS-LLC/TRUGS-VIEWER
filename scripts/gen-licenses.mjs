#!/usr/bin/env node
// Generate THIRD_PARTY_LICENSES and NOTICE from the installed dependency tree.
// Run `npm run license:gen` after a dependency change to keep attribution current.

import { writeFileSync } from "node:fs";
import process from "node:process";
import { collectReport, licenseOf } from "./license-report.mjs";

const report = collectReport();
const rows = Object.entries(report)
  .map(([name, info]) => ({ name, license: licenseOf(info), repo: info.repository ?? "" }))
  .sort((a, b) => a.name.localeCompare(b.name));

const header = `THIRD-PARTY SOFTWARE NOTICES AND LICENSES
=========================================

TRUGS-VIEWER (Apache-2.0) depends on the third-party packages listed below. Each is
distributed under its own license, identified here per the attribution obligations of
those licenses. Generated by scripts/gen-licenses.mjs from the resolved dependency tree
(node_modules) — do not hand-edit.

Total packages: ${rows.length}

`;

const body = rows
  .map((r) => `- ${r.name}\n    License: ${r.license}${r.repo ? `\n    Repository: ${r.repo}` : ""}`)
  .join("\n");

writeFileSync("THIRD_PARTY_LICENSES", header + body + "\n");

const notice = `TRUGS-VIEWER
Copyright (c) 2026 TRUGS LLC

This product is licensed under the Apache License, Version 2.0 (see LICENSE).

It includes third-party software under permissive licenses (MIT, ISC, BSD, Zlib,
Apache-2.0). The complete per-package attribution manifest is in THIRD_PARTY_LICENSES,
generated from the resolved dependency tree. Notable: the "postprocessing" package is
distributed under the Zlib license (not MIT).
`;
writeFileSync("NOTICE", notice);

console.log(`Wrote THIRD_PARTY_LICENSES (${rows.length} packages) and NOTICE.`);
process.exit(0);
